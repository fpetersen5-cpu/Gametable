import type { ChatLine, GameDef, GameView } from '@gametable/engine';
import type { GameAction, ReplayBundle, TranscriptPerspective } from '../shared/api.js';
import { visitSeatViews } from './replay.js';
import { validateTranscriptPerspective } from './validation.js';

/**
 * Public and seat exports consume only validated referee projections. Never
 * fall back to stored god views, raw events, final roles or debriefs when a
 * replay cannot be reconstructed. Omniscient export is a separate opt-in path.
 */
export function buildTranscript<S>(
  def: GameDef<S>, bundle: ReplayBundle, requested?: TranscriptPerspective,
): string {
  const perspective = validateTranscriptPerspective(requested);
  if (def.id !== bundle.summary.gameId) throw new Error('That game does not match the replay');
  if (perspective.mode === 'omniscient') return buildOmniscientTranscript(bundle);
  const ids = bundle.seats.map((seat) => seat.id);
  if (!ids.length || new Set(ids).size !== ids.length) throw new Error('Replay has an invalid seat roster');
  if (perspective.mode === 'seat' && !ids.includes(perspective.seatId)) {
    throw new Error('That seat is not in this replay');
  }
  const selected = perspective.mode === 'seat' ? [perspective.seatId] : ids;
  const { summary } = bundle;
  const names = new Map(bundle.seats.map((seat) => [seat.id, seat.name]));
  const seatName = perspective.mode === 'seat' ? names.get(perspective.seatId)! : null;
  const lines = [
    `# ${text(summary.gameName)} — ${text(summary.matchId)}`, '',
    `Perspective: ${seatName === null ? 'Public only' : `Seat — ${text(seatName)} (${text(selected[0]!)})`}`, '',
    seatName === null
      ? '> Public table talk and public record only. Private channels, hidden state and raw actions are excluded.'
      : '> PRIVATE SEAT TRANSCRIPT: includes this seat’s private knowledge and permitted private chat. Review before sharing.',
    '', `Played ${new Date(summary.startedAt).toISOString()}`,
    `Result: ${summary.winnerNames.map(text).join(', ') || 'no winner'}`, '',
    '## Seats', '', '| Seat | Kind | Model |', '|---|---|---|',
    ...bundle.seats.map((seat) => `| ${text(seat.name)} | ${seat.kind} | ${text(seat.modelId ?? '—')} |`), '',
  ];
  const chat: ChatLine[] = [];
  const seenChat = new Set<string>();
  const records: string[] = [];
  const privateStates: string[] = [];
  let previousRecord: string[] = [];
  let previousState = '';
  visitSeatViews(def, bundle, selected, (views, index) => {
    const first = views[0]!;
    const chatKeys = views.map((view) => new Set(view.chat.map((entry) => JSON.stringify(entry))));
    for (const line of first.chat) {
      if (perspective.mode === 'public' && line.channel !== 'public') continue;
      const key = JSON.stringify(line);
      if (!chatKeys.every((keys) => keys.has(key))) continue;
      if (!seenChat.has(key)) { seenChat.add(key); chat.push(line); }
    }
    const recordSets = views.map((view) => new Set(record(view)));
    const visible = record(first).filter((line) => recordSets.every((entries) => entries.has(line)));
    // Preserve repeated lines and rolling windows without repeating the entire
    // record at every action. No raw action description is used in this path.
    let overlap = Math.min(previousRecord.length, visible.length);
    while (overlap > 0 && JSON.stringify(previousRecord.slice(-overlap)) !== JSON.stringify(visible.slice(0, overlap))) {
      overlap--;
    }
    records.push(...visible.slice(overlap));
    previousRecord = visible;
    if (perspective.mode === 'seat') {
      const state = code({ phase: first.phase, data: first.data, legalActions: first.legalActions });
      if (state !== previousState) {
        privateStates.push(`### Projected step ${index}`, '', '```json', state, '```', '');
        previousState = state;
      }
    }
  });
  if (chat.length) {
    lines.push('## Table talk', '');
    for (const line of chat) {
      const channel = line.channel === 'public' ? '' : ` (${text(line.channel)})`;
      lines.push(`**${text(names.get(line.seatId) ?? line.seatId)}**${channel}: ${text(line.text)}`, '');
    }
  }
  lines.push('## Visible record', '', ...records.map((line) => `- ${text(line)}`), '');
  if (perspective.mode === 'seat') lines.push('## Seat-visible state', '', ...privateStates);
  lines.push('---', `Total cost $${summary.totalCostUsd.toFixed(4)} · generated by GameTable`, '');
  return lines.join('\n');
}

function record(view: GameView): string[] {
  const data = view.data as { log?: unknown; recent?: unknown } | null;
  const value = data?.log ?? data?.recent;
  return Array.isArray(value) ? value.filter((line): line is string => typeof line === 'string') : [];
}

/** Render untrusted speech as text, not HTML, images or Markdown links. */
function text(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/([`*_\[\]{}()#!|>])/g, '\\$1')
    .replace(/</g, '&lt;').replace(/\r?\n/g, ' ');
}

function code(value: unknown): string {
  return JSON.stringify(value, null, 2).replace(/`/g, '\\u0060').replace(/</g, '\\u003c');
}

/** Explicit full-information export. The main process must confirm it first. */
function buildOmniscientTranscript(bundle: ReplayBundle): string {
  const { summary, events, godViews } = bundle;
  const names = new Map(summary.seats.map((seat) => [seat.seatId, seat.name]));
  const finalView = godViews.at(-1);
  const finalData = finalView?.data as
    | { god?: { roles?: Record<string, string> } }
    | undefined;
  const roles = finalData?.god?.roles ?? {};

  const lines: string[] = [];
  lines.push(`# ${text(summary.gameName)} — ${text(summary.matchId)}`, '',
    'Perspective: Omniscient', '',
    '> WARNING: FULL PRIVATE RECORD. Contains hidden roles, private chat and raw actions. Do not share unless you intend to reveal everything.', '');
  lines.push(`Played ${new Date(summary.startedAt).toISOString()}`);
  lines.push(`Duration ${(summary.durationMs / 1000).toFixed(1)}s · ${events.length} actions`);
  lines.push(
    `Result: ${summary.winnerNames.length ? summary.winnerNames.map(text).join(', ') : 'no winner'}`,
    '',
  );

  lines.push('## Seats', '');
  lines.push('| Seat | Kind | Model | Role | Cost | Tokens in/out |');
  lines.push('|---|---|---|---|---|---|');
  for (const seat of summary.seats) {
    lines.push(
      `| ${text(seat.name)} | ${seat.kind} | ${text(seat.modelId ?? '—')} | ${
        text(seat.role ?? roles[seat.seatId] ?? '—')
      } | $${seat.costUsd.toFixed(4)} | ${seat.tokensIn}/${seat.tokensOut} |`,
    );
  }
  lines.push('');

  const chat = finalView?.chat ?? [];
  if (chat.length > 0) {
    lines.push('## Table talk', '');
    for (const line of chat) {
      const who = text(names.get(line.seatId) ?? line.seatId);
      const channel = line.channel === 'public' ? '' : ` (${text(line.channel)})`;
      lines.push(`**${who}**${channel}: ${text(line.text)}`, '');
    }
  }

  lines.push('## Actions', '');
  events.forEach((event, index) => {
    const who = text(names.get(event.seatId) ?? event.seatId);
    const round = event.round !== undefined ? `, round ${event.round}` : '';
    lines.push(`${index + 1}. ${text(event.phaseId)}${round} — **${who}** ${text(describe(event.action))}`);
  });

  if (Object.keys(summary.metrics).length > 0) {
    lines.push('', '## Table metrics', '');
    for (const [key, value] of Object.entries(summary.metrics)) {
      lines.push(`- ${text(key)}: ${value}`);
    }
  }

  lines.push(
    '',
    '---',
    `Total cost $${summary.totalCostUsd.toFixed(4)} · generated by GameTable`,
    '',
  );
  return lines.join('\n');
}

function describe(action: GameAction): string {
  const { type, ...rest } = action;
  const detail = Object.entries(rest)
    .map(([key, value]) => `${key}=${JSON.stringify(value)}`)
    .join(' ');
  return detail ? `${type} (${detail})` : type;
}
